            {6'd45, 3'd1}: font = 8'h10;
            {6'd45, 3'd2}: font = 8'h20;
            {6'd45, 3'd3}: font = 8'h20;
            {6'd45, 3'd4}: font = 8'h20;
            {6'd45, 3'd5}: font = 8'h10;
